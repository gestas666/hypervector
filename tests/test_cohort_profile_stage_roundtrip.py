"""Regression checks for exact staged direction and entry-slippage preservation."""

from __future__ import annotations

from dataclasses import replace
from pathlib import Path

import pytest

from hypervector.live import cohort_profile_stage
from hypervector.live.cohort_operator_commands import (
    CohortAssetStage,
    CohortProfileSettings,
    CohortProviderStage,
)
from hypervector.live.multi_asset_live_config import (
    MultiAssetLiveConfig,
    load_multi_asset_live_config,
)

V89 = Path('tests/fixtures/profiles/multi_asset_growth_first_5000_noncrypto_live_v89.toml')
CANARY = Path('tests/fixtures/profiles/multi_asset_bidirectional_canary.toml')


def unchanged_settings(config: MultiAssetLiveConfig) -> CohortProfileSettings:
    """Keep editable values identical so serialization drift is directly observable."""
    return CohortProfileSettings(
        maximum_positions=config.maximum_positions,
        poll_seconds=config.poll_seconds,
        assets=tuple(CohortAssetStage(a.symbol, a.leverage, a.margin_fraction,
                                     a.max_notional_usd, a.stop_bps, a.maximum_hold_seconds)
                     for a in config.assets),
        providers=tuple(CohortProviderStage(p.strategy_id, p.execution_symbols)
                        for p in config.providers),
    )


def test_exact_v89_stage_preserves_all_provider_contracts(tmp_path: Path) -> None:
    """The actual seven-asset profile must load with unchanged provider contracts."""
    original_bytes = V89.read_bytes()
    original = load_multi_asset_live_config(V89, mode='observe')
    output = tmp_path / 'v89-staged.toml'
    cohort_profile_stage.stage_cohort_profile(config=original, settings=unchanged_settings(original), output_path=output)
    candidate = load_multi_asset_live_config(output, mode='observe')
    assert candidate.providers == original.providers
    assert candidate.executable_provider_directions == original.executable_provider_directions
    assert candidate.transition_approval is None
    assert not candidate.enabled and not candidate.accepts_live_risk
    assert all(not asset.enabled and not asset.accepts_live_risk for asset in candidate.assets)
    assert V89.read_bytes() == original_bytes


def test_narrow_asset_scope_remains_invalid(tmp_path: Path) -> None:
    """The existing two-direction asset envelope rule is not weakened by this fix."""
    original = load_multi_asset_live_config(V89, mode='observe')
    assets = tuple(replace(a, sides=frozenset({'long'})) if a.symbol == 'BTC' else a for a in original.assets)
    original = replace(original, assets=assets)
    output = tmp_path / 'narrow.toml'
    with pytest.raises(ValueError, match='must support both long and short'):
        cohort_profile_stage.stage_cohort_profile(config=original, settings=unchanged_settings(original), output_path=output)
    assert not output.exists()


@pytest.mark.parametrize('entry_cap', [None, 0.002])
def test_entry_cap_and_legacy_fallback_survive(tmp_path: Path, entry_cap: float | None) -> None:
    """An explicit entry cap stays distinct from the legacy shared market cap."""
    original = load_multi_asset_live_config(CANARY, mode='observe')
    assets = tuple(replace(a, entry_slippage_cap_fraction=entry_cap, market_slippage_cap_fraction=0.01)
                   for a in original.assets)
    original = replace(original, assets=assets)
    output = tmp_path / 'slippage.toml'
    cohort_profile_stage.stage_cohort_profile(config=original, settings=unchanged_settings(original), output_path=output)
    candidate = load_multi_asset_live_config(output, mode='observe')
    assert [a.entry_slippage_cap_fraction for a in candidate.assets] == [entry_cap] * len(assets)
    assert [a.effective_entry_slippage_cap_fraction for a in candidate.assets] == [a.effective_entry_slippage_cap_fraction for a in assets]


def test_failed_serialized_validation_preserves_existing_output(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """Validate generated bytes before replacing an existing staged configuration."""
    original = load_multi_asset_live_config(CANARY, mode='observe')
    output = tmp_path / 'staged.toml'
    output.write_bytes(b'prior staged file')
    def broken_serializer(_: MultiAssetLiveConfig) -> str:
        """Return malformed generated configuration for atomic-publication testing."""
        return 'profile = "incomplete"\n'
    monkeypatch.setattr(cohort_profile_stage, '_toml', broken_serializer)
    with pytest.raises(ValueError):
        cohort_profile_stage.stage_cohort_profile(config=original, settings=unchanged_settings(original), output_path=output)
    assert output.read_bytes() == b'prior staged file'
    assert sorted(p.name for p in tmp_path.iterdir()) == ['staged.toml']


def test_valid_but_changed_serialization_is_rejected(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """A loadable serializer regression must not publish changed trading semantics."""
    original = load_multi_asset_live_config(CANARY, mode='observe')
    serializer = cohort_profile_stage._toml
    def omit_entry_cap(config: MultiAssetLiveConfig) -> str:
        """Simulate a future lossy serializer without changing its input object."""
        return serializer(replace(config, assets=tuple(replace(a, entry_slippage_cap_fraction=None) for a in config.assets)))
    original = replace(original, assets=tuple(replace(a, entry_slippage_cap_fraction=0.002) for a in original.assets))
    monkeypatch.setattr(cohort_profile_stage, '_toml', omit_entry_cap)
    with pytest.raises(ValueError, match='fingerprint'):
        cohort_profile_stage.stage_cohort_profile(config=original, settings=unchanged_settings(original), output_path=tmp_path / 'bad.toml')
    assert list(tmp_path.iterdir()) == []


def test_flat_entry_position_policy_survives(tmp_path: Path) -> None:
    """A supported flat-entry-only provider must not gain position-close authority."""
    original = load_multi_asset_live_config('tests/fixtures/profiles/multi_asset_bidirectional_hype_relaxed_candidate.toml', mode='observe')
    assert any(p.position_policy == 'flat_entry_only' for p in original.providers)
    output = tmp_path / 'flat-entry.toml'
    cohort_profile_stage.stage_cohort_profile(config=original, settings=unchanged_settings(original), output_path=output)
    candidate = load_multi_asset_live_config(output, mode='observe')
    assert candidate.providers == original.providers


def test_publish_failure_preserves_prior_file(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """An operating-system publication error propagates and removes only its temporary file."""
    original = load_multi_asset_live_config(CANARY, mode='observe')
    output = tmp_path / 'staged.toml'
    output.write_bytes(b'prior staged file')
    def fail_replace(source: Path, destination: Path) -> None:
        """Model a failed rename without modifying either existing file."""
        raise PermissionError('test publication denied')
    monkeypatch.setattr(cohort_profile_stage.os, 'replace', fail_replace)
    with pytest.raises(PermissionError, match='publication denied'):
        cohort_profile_stage.stage_cohort_profile(config=original, settings=unchanged_settings(original), output_path=output)
    assert output.read_bytes() == b'prior staged file'
    assert sorted(p.name for p in tmp_path.iterdir()) == ['staged.toml']
